#!/usr/bin/env python3
"""Deterministic precompressed public assets and entry's fixed allowlist metadata."""
from pathlib import Path
import gzip,hashlib,json,re
root=Path(__file__).resolve().parent;www=root/'dist/www'
(root/'build').mkdir(parents=True,exist_ok=True)
version=re.search(r'#define VERSION "([^"]+)"',(root/'api.c').read_text())[1]
names=['index.html','app.css','app.js','events.js','sms-codec.js','communications.js','call-audio.js','audio.js','pcm-worklet.js']
records=[]
for name in names:
 raw=(www/name).read_bytes();packed=gzip.compress(raw,compresslevel=9,mtime=0);(www/(name+'.gz')).write_bytes(packed)
 records.append({'name':name,'sha256':hashlib.sha256(raw).hexdigest(),'rawBytes':len(raw),'gzipBytes':len(packed)})
header='/* Generated by prepare-web-assets.py; fixed public files only. */\n#define WEB_ASSET_VERSION '+json.dumps(version)+'\n'
header+='typedef struct {const char *name,*hash;size_t raw_size,gzip_size;} WebAsset;\nstatic const WebAsset web_assets[]={\n'
header+=''.join('{'+json.dumps(x['name'])+','+json.dumps(x['sha256'])+','+str(x['rawBytes'])+','+str(x['gzipBytes'])+'},\n' for x in records)+'};\n'
(root/'build/static-assets.h').write_text(header)
report={'version':version,'assets':records,'rawBytes':sum(x['rawBytes'] for x in records),'gzipBytes':sum(x['gzipBytes'] for x in records)}
(root/'build/web-assets-size.json').write_text(json.dumps(report,indent=2)+'\n')
print('Public asset bytes:',report['rawBytes'],'-> gzip:',report['gzipBytes'])
